// Writes src/abi.ts from the compiled artifact so the agent runs without compiling contracts.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync("artifacts/contracts/DeliveryEscrow.sol/DeliveryEscrow.json", "utf8"),
);
writeFileSync(
  "src/abi.ts",
  `// Generated by scripts/export-abi.ts - do not edit.\nexport const escrowAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log("wrote src/abi.ts");
